let currentLang = localStorage.getItem('vox_lang') || 'en';

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('vox_lang', lang);

  document.querySelectorAll('[data-key]').forEach(el => {
    const key = el.getAttribute('data-key');
    if (content[lang][key] !== undefined) {
      el.innerHTML = content[lang][key];
    }
  });

  document.getElementById('btn-en').classList.toggle('active', lang === 'en');
  document.getElementById('btn-es').classList.toggle('active', lang === 'es');
  document.documentElement.lang = lang;
}

document.getElementById('btn-en').addEventListener('click', () => applyLang('en'));
document.getElementById('btn-es').addEventListener('click', () => applyLang('es'));

// Apply on load
applyLang(currentLang);